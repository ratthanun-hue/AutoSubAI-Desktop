  let currentLang = localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'th';

  function t(key) {
    return (DICT[currentLang] && DICT[currentLang][key]) || DICT.th[key] || key;
  }

  function applyDom() {
    document.documentElement.lang = currentLang;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const k = el.getAttribute('data-i18n');
      if (k) el.textContent = t(k);
    });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      const k = el.getAttribute('data-i18n-ph');
      if (k) el.setAttribute('placeholder', t(k));
    });
    const thBtn = document.getElementById('ui-lang-th');
    const enBtn = document.getElementById('ui-lang-en');
    if (thBtn) thBtn.classList.toggle('active', currentLang === 'th');
    if (enBtn) enBtn.classList.toggle('active', currentLang === 'en');
  }

  function setLang(lang) {
    currentLang = lang === 'en' ? 'en' : 'th';
    localStorage.setItem(STORAGE_KEY, currentLang);
    applyDom();
    window.dispatchEvent(new CustomEvent('autosub-lang-changed', { detail: { lang: currentLang } }));
  }

  function getLang() {
    return currentLang;
  }

  window.DesktopI18n = { t, setLang, getLang, applyDom };
